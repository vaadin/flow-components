package com.vaadin.flow.component.charts.internal;

import java.io.File;
import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.util.List;
import java.util.Set;
import java.util.regex.Pattern;

import org.slf4j.LoggerFactory;

import com.vaadin.flow.server.frontend.Options;
import com.vaadin.flow.server.frontend.TypeScriptBootstrapModifier;
import com.vaadin.flow.server.frontend.scanner.ClassFinder;

/**
 * Generates a frontend module that registers, as real functions, the JavaScript
 * function sources that the application passes to the {@code _fn_} setters of
 * the Charts model. {@code <vaadin-chart>} looks a source up in that registry
 * before it falls back to evaluating it, so the functions found at build time
 * run without {@code eval}.
 * <p>
 * Flow finds this class through the class finder and runs it when it generates
 * the bootstrap file.
 * <p>
 * For internal use only. May be renamed or removed in a future release.
 */
public class ChartFunctionsBootstrapModifier
        implements TypeScriptBootstrapModifier {

    static final String FILE_NAME = "vaadin-chart-functions.js";

    private static final Pattern FUNCTION_EXPRESSION = Pattern.compile(
            "^(async\\s+)?function\\b|^(async\\s+)?(\\([^)]*\\)|[A-Za-z_$][\\w$]*)\\s*=>");

    @Override
    public void modify(List<String> bootstrapTypeScript, Options options) {
        ClassFinder classFinder = options.getClassFinder();
        ChartFunctionScanner scanner = new ChartFunctionScanner(name -> {
            try {
                return classFinder.loadClass(name);
            } catch (ClassNotFoundException e) {
                throw new IllegalStateException(e);
            }
        });
        Set<String> sources = scanner
                .scanClassLoader(classFinder.getClassLoader());
        LoggerFactory.getLogger(ChartFunctionsBootstrapModifier.class).debug(
                "Found {} Charts function sources to bundle", sources.size());

        File file = new File(options.getFrontendGeneratedFolder(), FILE_NAME);
        writeIfChanged(file, generate(sources));
        bootstrapTypeScript.add(String.format("import './%s';", FILE_NAME));
    }

    /**
     * Generates the module that registers the given function sources.
     *
     * @param sources
     *            the function sources
     * @return the content of the module
     */
    static String generate(Set<String> sources) {
        StringBuilder content = new StringBuilder();
        content.append("// Generated by vaadin-charts-flow. Do not edit.\n");
        content.append("window.Vaadin = window.Vaadin || {};\n");
        content.append(
                "const registry = (window.Vaadin.chartFunctions = window.Vaadin.chartFunctions || new Map());\n");
        for (String source : sources) {
            content.append("registry.set(").append(toJsString(source))
                    .append(", ").append(toFunction(source)).append(");\n");
        }
        return content.toString();
    }

    /**
     * Turns a source into a function expression, the same way as the
     * {@code eval} fallback in {@code <vaadin-chart>}: a source that is a
     * function expression is used as it is, anything else is the body of a
     * function.
     */
    static String toFunction(String source) {
        // A trailing semicolon is not valid inside the parentheses
        String trimmed = source.strip().replaceAll(";+$", "").strip();
        if (FUNCTION_EXPRESSION.matcher(trimmed).find()) {
            return "(\n" + trimmed + "\n)";
        }
        return "function () {\n" + source + "\n}";
    }

    static String toJsString(String value) {
        StringBuilder result = new StringBuilder("\"");
        for (char c : value.toCharArray()) {
            switch (c) {
            case '"' -> result.append("\\\"");
            case '\\' -> result.append("\\\\");
            case '\n' -> result.append("\\n");
            case '\r' -> result.append("\\r");
            case '\t' -> result.append("\\t");
            default -> {
                if (c < 0x20 || c == 0x2028 || c == 0x2029) {
                    result.append(String.format("\\u%04x", (int) c));
                } else {
                    result.append(c);
                }
            }
            }
        }
        return result.append('"').toString();
    }

    private static void writeIfChanged(File file, String content) {
        try {
            if (file.exists() && content.equals(
                    Files.readString(file.toPath(), StandardCharsets.UTF_8))) {
                return;
            }
            Files.createDirectories(file.toPath().getParent());
            Files.writeString(file.toPath(), content, StandardCharsets.UTF_8);
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }
}
